"""Builds hooks/pokedex.ts from a checkout of jakobhoeg/vscode-pokemon (CC0 code; no sprites are copied)."""
import json, os, re, sys

upstream, out = sys.argv[1], sys.argv[2]
src = open(os.path.join(upstream, 'src/common/pokemon-data.ts')).read()
entry = re.compile(r"^  ([a-z0-9_]+): \{\n(.*?)^  \},", re.S | re.M)
locales = {'fr': 'fr-FR', 'de': 'de-DE', 'ja': 'ja-JP'}
names = {}
for short, loc in locales.items():
    for g in range(1, 6):
        p = os.path.join(upstream, 'l10n/pokemon', loc, f'gen{g}.json')
        if os.path.exists(p):
            for k, v in json.load(open(p)).items():
                names.setdefault(k, {})[short] = v
rows = []
for key, body in entry.findall(src):
    name = re.search(r"name: (['\"])(.*?)\1,", body).group(2)
    gen = int(re.search(r"PokemonGeneration\.Gen(\d)", body).group(1))
    media = os.path.join(upstream, 'media', f'gen{gen}', key)
    # Upstream lists some Pokémon it has no sprites for yet; skip those.
    if not all(os.path.exists(os.path.join(media, f'default_{a}_8fps.gif')) for a in ('idle', 'walk')):
        continue
    shiny = all(os.path.exists(os.path.join(media, f'shiny_{a}_8fps.gif')) for a in ('idle', 'walk'))
    left = os.path.exists(os.path.join(media, 'default_walk_left_8fps.gif'))
    row = [key, name, gen, int(shiny), int(left)]
    loc = names.get(key, {})
    row.append({k: v for k, v in loc.items() if v != name})
    rows.append(row)
with open(out, 'w') as f:
    f.write('// Generated by scripts/build-pokedex.py from jakobhoeg/vscode-pokemon (CC0). Do not edit.\n')
    f.write('// [key, English name, generation, has shiny, has left-facing walk, other-language names]\n')
    f.write('export const POKEDEX_ROWS: ReadonlyArray<\n  readonly [string, string, number, number, number, Readonly<Record<string, string>>]\n> = [\n')
    for r in rows:
        f.write('  ' + json.dumps(r, ensure_ascii=False) + ',\n')
    f.write(']\n')
print(len(rows), 'entries')
